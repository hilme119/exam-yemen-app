# Save CSV with UTF-8 BOM so Excel opens Arabic correctly
csv_file = "g:/Dev-Projects/Flutter/ExamYemen/quran_exam_p9.csv"
with open(csv_file, 'w', newline='', encoding='utf-8-sig') as f:
    writer = csv.writer(f)
    writer.writerow(headers)
    for item in data:
        writer.writerow([
            item["text"],
            item["type"],
            item["opt1"],
            item["opt2"],
            item["opt3"],
            item["opt4"],
            item["ans"]
        ])

# Save JSON
json_file = "g:/Dev-Projects/Flutter/ExamYemen/quran_exam_p9.json"
json_data = []
for i, item in enumerate(data, 1):
    opts = [item["opt1"], item["opt2"]]
    if item["type"] == "MCQ":
        opts.extend([item["opt3"], item["opt4"]])
    json_data.append({
        "id": f"quran_p9_{i}",
        "number": i,
        "question": item["text"],
        "type": "true_false" if item["type"] == "TF" else "mcq",
        "options": opts,
        "correctAnswerIndex": item["ans"]
    })

with open(json_file, 'w', encoding='utf-8') as f:
    json.dump({
        "exam_info": {
            "title": "اختبار القرآن الكريم - الشهادة الأساسية (الصف التاسع)",
            "year": "2025/2026 - 1447هـ",
            "form_code": "P.9",
            "total_questions": len(data)
        },
        "questions": json_data
    }, f, ensure_ascii=False, indent=2)

